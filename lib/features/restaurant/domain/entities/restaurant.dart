class Restaurant {
  final int id;
  final String name;
  final String image;
  final String description;
  final double rating;
  final String delivery;
  final String deliveryTime;

  const Restaurant({
    required this.id,
    required this.name,
    required this.image,
    required this.description,
    required this.rating,
    required this.delivery,
    required this.deliveryTime,
  });
}