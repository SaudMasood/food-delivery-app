class Food {
  final int id;
  final String name;
  final String image;
  final double price;
  final String category;
  final String restaurant;
  final double rating;

  const Food({
    required this.id,
    required this.name,
    required this.image,
    required this.price,
    required this.category,
    required this.restaurant,
    required this.rating,
  });
}